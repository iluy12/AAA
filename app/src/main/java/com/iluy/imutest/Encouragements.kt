package com.iluy.imutest

/**
 * מאגר חיזוקים להתגברות.
 *
 * **למה מאגר ולא טקסט קבוע:** המחווה נעשית כמה פעמים ביום. הודעה זהה
 * בכל פעם מאבדת משמעות תוך יומיים והופכת לרעש. גיוון שומר על זה חי.
 *
 * **הטון:** ✕ הוא הצלחה, ולכן כל הטקסטים כאן מחזקים ולא מודאגים. גם
 * ההודעה שמופיעה בסף האישי — "התגברת שוב ושוב היום" — היא מחמאה,
 * לא אזהרה. מי שהתגבר חמש פעמים ביום לא צריך לשמוע שמשהו לא בסדר איתו.
 */
object Encouragements {

    /** לכל התגברות רגילה. קצר — המסך נסגר לבד אחרי כמה שניות. */
    private val ordinary = listOf(
        "נשמר. אלוף",
        "יפה מאוד",
        "כל הכבוד",
        "השם רואה את המאמץ שלך",
        "זו בדיוק העבודה",
        "חזק",
        "עוד אחת בכיס",
        "נרשם. אשריך"
    )

    /**
     * כשמגיעים לסף האישי — כלומר עברת את מה שדיווחת שאתה בדרך כלל
     * מחזיק. מכיר במאמץ במפורש.
     */
    private val atThreshold = listOf(
        "התגברת שוב ושוב היום. זה לא מובן מאליו",
        "אתה מחזיק חזק היום. שים לב לעצמך",
        "כמה פעמים כבר אמרת לא היום. אלוף",
        "יום לא פשוט, ואתה עומד בו"
    )

    /**
     * רמיזה עדינה לשיחה עם מלווה. מופיעה רק חלק מהפעמים בסף — כדי
     * שלא תיהפך לנודניקית ותיבלע.
     */
    /**
     * ⚠️ **אלה שאלות עכשיו, לא רמזים.** קודם הן נוספו כשורה שנייה מתחת
     * לחיזוק, ואי-אפשר היה לענות עליהן — כלומר הן היו טקסט שנעלם. נבו
     * ניסח אותן מחדש כשאלה ("נלך על זה?"), ולפי הכלל שקבע כל שאלה מקבלת
     * כן/לא: **כן מרימה שיחה, לא עונה "אם צריך אני כאן".**
     *
     * ⚠️ ולכן הן גם מופיעות **פחות** מבעבר. רמז שנבלע עולה כלום; שאלה
     * דורשת תגובה, ולכן היא מטרידה יותר ומגיעה בערך פעם מארבע.
     */
    private val mentorHints = listOf(
        "שיחה קצרה עם מלווה יכולה לאפס אותך, נלך על זה?",
        "מותר גם לבקש עזרה. רוצה שנתקשר?",
        "מלווה זמין בשבילך עכשיו. להרים טלפון?"
    )

    fun mentorQuestion(): String = mentorHints.random()

    /**
     * השבועות הראשונים, לפני שיש בסיס.
     *
     * ⚠️ **אומר את האמת ולא מבטיח.** המערכת באמת עוד לא יודעת כלום עליו,
     * ולהעמיד פנים שהיא כן — זה מה שישרוף את האמון כשההצעה הראשונה תחטיא.
     * הכנות כאן היא גם מה שמזמין אותו לשתף.
     */
    private val learning = listOf(
        Line("בימים הראשונים אני בעיקר מקשיב. כל סימון שלך מחדד לי את התמונה"),
        Line("עוד לא מכיר אותך מספיק. תן לי כמה ימים ונתקדם ביחד"),
        Line("אתה מלמד אותי בכל פעם שאתה מסמן. תמשיך"),
        Line("לאט לאט אני לומד מתי קשה לך. זה לוקח זמן, וזה בסדר")
    )

    /**
     * יום שבו הוא התגבר הרבה מעל הממוצע השבועי שלו.
     *
     * ⚠️ **מכיר במאמץ, לא מודאג.** מי שהתגבר עשר פעמים ביום לא צריך לשמוע
     * שמשהו לא בסדר איתו — הוא צריך לשמוע שרואים אותו. ניסוח מדאיג כאן
     * הופך הצלחה לאזהרה.
     */
    private val roughDay = listOf(
        Line("יום עמוס. וכל פעם שאמרת לא — היא נספרת למעלה"),
        Line("היום אתה עובד קשה. תדע שזה נראה"),
        Line("יום כזה מגיע לך שתדע: אתה מחזיק חזק"),
        Line("הרבה סיבובים היום, וקמת בכולם"),
        Line("יום כזה שווה שיחה עם מלווה, לא בגלל שנפלת אלא בגלל שהחזקת. נדבר?", isQuestion = true)
    )

    /**
     * ההצעה היזומה — כשהמערכת מזהה רגע מסוכן, **לפני** שקרה משהו.
     *
     * ⚠️⚠️ **הבנק הרגיש ביותר במוצר, ויש לו חוק אחד שאסור לשבור:**
     *
     * > **אף אחד מהמשפטים כאן לא רומז שהמערכת יודעת משהו.**
     *
     * שתי סיבות, ושתיהן מהותיות. הראשונה: המשתמש צריך **סיבה לקום שאיננה
     * "השעון תפס אותי"** — אפילו מול עצמו. רמז כאן מוסיף בושה בדיוק ברגע
     * שבו בושה היא הדבר האחרון שעוזר. השנייה: **כשמחיר הטעות אפס, דיוק
     * בינוני מספיק** — וזה מה שמאפשר את המוצר בכלל. משפט שמסגיר זיהוי
     * הופך כל טעות למחיר.
     *
     * לכן אין כאן שאלות כן/לא. שאלה מחייבת תשובה, ותשובה הופכת את זה
     * לאירוע. **הצעה טובה כאן היא כזו שאפשר להתעלם ממנה בלי להרגיש כלום.**
     */
    private val gentleOffer = listOf(
        Line("רוצה לקום לכמה דקות?"),
        Line("אולי כדאי למתוח קצת"),
        Line("מה דעתך לשתות משהו?"),
        Line("רגע של אוויר?"),
        Line("שווה לקום לרגע"),
        Line("אולי זה זמן טוב לצאת קצת"),
        Line("תנוחה חדשה עושה טוב")
    )

    /**
     * לא דיווח כמה ימים.
     *
     * ⚠️ **אפס דיווחים הוא דו-משמעי:** או שהוא מחזיק, או שהוא נעלם. שתי
     * המשמעויות הפוכות, והדרך היחידה לדעת היא לשאול. לכן רוב הבנק הזה
     * שאלות ולא הצהרות.
     */
    private val silentTooLong = listOf(
        Line("מזמן לא סימנת. הכל טוב או ששכחת?", isQuestion = true),
        Line("שקט אצלך כמה ימים. רוצה לדבר רגע?", isQuestion = true),
        Line("רק מזכיר שאני כאן. כל סימון עוזר לי להכיר אותך"),
        Line("לא ראיתי אותך כמה ימים. אתה בסדר?", isQuestion = true)
    )

    fun learning(): Line = learning.random()
    fun roughDay(): Line = roughDay.random()
    fun gentleOffer(): String = gentleOffer.random().text
    fun silentTooLong(): Line = silentTooLong.random()

    /**
     * ⚠️ **שלושת הבנקים הבאים הם מצייני-מקום. המילים חייבות להיות של נבו.**
     *
     * זה הרגע הרגיש ביותר במוצר — מבקשים מבחור לדווח על נפילה ברגע של
     * בושה. הניסוח כאן הוא ההבדל בין פיצ'ר שעובד לפיצ'ר שנזנח, ואני לא
     * הכתובת לכתוב אותו.
     */

    /**
     * הודעה, ואם היא שאלה — היא דורשת תשובת כן/לא.
     *
     * ⚠️ **הכלל שקבע נבו:** בכל מקום שיש שאלה, מוצגים "כן" ו"לא".
     * **"כן" מרימה שיחה למלווה. "לא" עונה "אם צריך אני כאן" ונסגר.**
     * הודעה שהיא שאלה בלי דרך לענות היא רק עוד טקסט שנעלם.
     */
    data class Line(val text: String, val isQuestion: Boolean = false)

    /** התשובה ל"לא". לא מנדנדת, לא חוזרת. */
    const val DECLINE_REPLY = "אם צריך אני כאן"

    /**
     * הרגע עצמו: קצר, **סוגר**, בלי שאלות. המסך נעלם מיד אחריו.
     * זה לא הזמן לדבר איתו.
     */
    private val fallAcknowledge = listOf(
        "תודה שדיווחת",
        "קיבלתי",
        "בסדר, אני כאן"
    )

    /**
     * 5-15 דקות אחר כך: **פותח**, לא סוגר. אחרי שהרגע החריף עבר.
     * מעודד ומניע לפעולה, בלי לתחקר.
     */
    private val afterFirstFall = listOf(
        Line("אתה אריה, ואתה נלחם להשתנות. וזה מה שחשוב לה'"),
        Line("תחזיק חזק באמונה ובשמחה. אתה בדרך!"),
        Line("המאמצים שלך מגיעים עד כיסא הכבוד"),
        Line("מצווה גדולה להיות בשמחה!"),
        Line("רוצה נתחזק ביחד?", isQuestion = true),
        Line("אתה לא לבד בזה, ואתה בדרך!")
    )

    /**
     * נפילה שנייה באותו יום. ⚠️ יותר מאחת ביום היא סימן להתדרדרות, ולכן
     * **ישיר ולא רומז** — ומגיע מהר יותר.
     */
    private val afterSecondFall = listOf(
        Line("יום קשה. תרים טלפון למלווה ותצא מזה"),
        Line("אין ייאוש בעולם. הכל יהיה בסדר"),
        Line("רוצה לדבר 2 דקות להתאפס?", isQuestion = true),
        Line("רוצה נתעודד בטלפון?", isQuestion = true),
        Line("אתה בדרך ליעד. כל אחד יכול לפספס פניה בדרך"),
        Line("תרים את הראש - אתה בן של מלך")
    )

    /**
     * ⚠️ **בנק מקביל לכל סוג נפילה.** נבו: *"גם הבנק של החיזוקים צריך
     * להיות מקביל לאותו סוג דיווח."*
     *
     * הסיבה שזה נכון: מי שנפל במחשבה ומי שנפל בברית הם בשני מצבים שונים
     * לגמרי, ומשפט אחד שמתאים לשניהם לא מתאים לאף אחד. **וגנרי נשחק תוך
     * שבוע.**
     */
    private val afterThought = listOf(
        Line("מחשבה היא לא מעשה. תפסת את זה, וזה בדיוק העבודה"),
        Line("זה בא והלך. אתה עדיין בדרך"),
        Line("שים לב לעצמך היום, ותמשיך"),
        Line("מצווה גדולה להיות בשמחה!")
    )

    /**
     * ⚠️ עיניים — נבו: *"צפויים לו ניסיונות קשים ביומיים הקרובים."*
     * הטון כאן מכין אותו לימים הבאים, לא רק מנחם על מה שהיה.
     */
    private val afterEyes = listOf(
        Line("היומיים הקרובים יהיו קצת יותר קשים. תדע את זה מראש ותהיה מוכן"),
        Line("עכשיו הזמן לשמור על העיניים כפליים. אתה יכול"),
        Line("אתה בדרך ליעד. כל אחד יכול לפספס פניה בדרך"),
        Line("רוצה שנדבר על היומיים הקרובים?", isQuestion = true)
    )

    fun fallAcknowledge(): String = fallAcknowledge.random()

    /**
     * החיזוק המושהה, לפי חומרת הנפילה ולפי אם זו השנייה היום.
     *
     * ⚠️ נפילה שנייה גוברת על הסיווג — יותר מאחת ביום היא תמיד סימן
     * להתדרדרות, ואז הטון הישיר חשוב יותר מהתאמה לקטגוריה.
     */
    fun afterFall(severity: FallSeverity, secondToday: Boolean): Line = when {
        secondToday -> afterSecondFall.random()
        severity == FallSeverity.THOUGHT -> afterThought.random()
        severity == FallSeverity.EYES -> afterEyes.random()
        else -> afterFirstFall.random()
    }

    fun afterFirstFall(): Line = afterFirstFall.random()
    fun afterSecondFall(): Line = afterSecondFall.random()

    fun ordinary(): String = ordinary.random()

    /**
     * @param withMentorHint האם לצרף רמיזת-מלווה. מופעל בערך בשליש
     *        מהפעמים על-ידי הקורא, לא כאן, כדי שההחלטה תהיה גלויה.
     */
    /**
     * ⚠️ **כבר לא מקבל את רמיזת-המלווה.** הרמיזה הפכה לשאלה עם כן/לא,
     * ולכן היא מסך נפרד שנפתח אחרי החיזוק — ראו [mentorQuestion] ואת
     * `EXTRA_ASK_AFTER` ב-TapAcknowledgedActivity. שאלה שנדחסת כשורה
     * שנייה מתחת לחיזוק אי-אפשר לענות עליה.
     */
    fun atThreshold(): String = atThreshold.random()
}
