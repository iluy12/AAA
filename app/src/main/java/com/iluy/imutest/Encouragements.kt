package com.iluy.imutest

/**
 * מאגר חיזוקים להתגברות.
 *
 * **למה מאגר ולא טקסט קבוע:** המחווה נעשית כמה פעמים ביום. הודעה זהה
 * בכל פעם מאבדת משמעות תוך יומיים והופכת לרעש. גיוון שומר על זה חי.
 *
 * **הטון:** ✕ הוא הצלחה, ולכן כל הטקסטים כאן מחזקים ולא מודאגים. גם
 * ההודעה שמופיעה בסף האישי — "התגברת שוב ושוב היום" — היא מחמאה,
 * לא אזהרה. מי שהתגבר חמש פעמים ביום לא צריך לשמוע שמשהו לא בסדר איתו.
 */
object Encouragements {

    /** לכל התגברות רגילה. קצר — המסך נסגר לבד אחרי כמה שניות. */
    private val ordinary = listOf(
        "נשמר. אלוף",
        "יפה מאוד",
        "כל הכבוד",
        "השם רואה את המאמץ שלך",
        "זו בדיוק העבודה",
        "חזק",
        "עוד אחת בכיס",
        "נרשם. אשריך"
    )

    /**
     * כשמגיעים לסף האישי — כלומר עברת את מה שדיווחת שאתה בדרך כלל
     * מחזיק. מכיר במאמץ במפורש.
     */
    private val atThreshold = listOf(
        "התגברת שוב ושוב היום. זה לא מובן מאליו",
        "אתה מחזיק חזק היום. שים לב לעצמך",
        "כמה פעמים כבר אמרת לא היום. אלוף",
        "יום לא פשוט, ואתה עומד בו"
    )

    /**
     * רמיזה עדינה לשיחה עם מלווה. מופיעה רק חלק מהפעמים בסף — כדי
     * שלא תיהפך לנודניקית ותיבלע.
     */
    private val mentorHints = listOf(
        "לפעמים שיחה קצרה עם מלווה עושה את כל ההבדל",
        "מותר גם לבקש עזרה. זה חלק מהכוח",
        "מלווה זמין בשבילך, גם בלי סיבה מיוחדת"
    )

    /**
     * ⚠️ **שלושת הבנקים הבאים הם מצייני-מקום. המילים חייבות להיות של נבו.**
     *
     * זה הרגע הרגיש ביותר במוצר — מבקשים מבחור לדווח על נפילה ברגע של
     * בושה. הניסוח כאן הוא ההבדל בין פיצ'ר שעובד לפיצ'ר שנזנח, ואני לא
     * הכתובת לכתוב אותו.
     */

    /**
     * הרגע עצמו: קצר, **סוגר**, בלי שאלות. המסך נעלם מיד אחריו.
     * זה לא הזמן לדבר איתו.
     */
    private val fallAcknowledge = listOf(
        "נרשם.",
        "קיבלתי.",
        "בסדר. אני כאן"
    )

    /**
     * 5-15 דקות אחר כך: **פותח**, לא סוגר. אחרי שהרגע החריף עבר.
     * מעודד ומניע לפעולה, בלי לתחקר.
     */
    private val afterFirstFall = listOf(
        "מחר זה יום חדש. אתה לא לבד בזה",
        "נפילה אחת לא מוחקת את כל מה שעשית",
        "אתה עדיין בדרך. שיחה קצרה עם מלווה יכולה לעזור עכשיו"
    )

    /**
     * נפילה שנייה באותו יום. ⚠️ יותר מאחת ביום היא סימן להתדרדרות, ולכן
     * **ישיר ולא רומז** — ומגיע מהר יותר.
     */
    private val afterSecondFall = listOf(
        "יום קשה. עכשיו זה הזמן להרים טלפון למלווה",
        "אל תישאר עם זה לבד היום. תתקשר"
    )

    fun fallAcknowledge(): String = fallAcknowledge.random()
    fun afterFirstFall(): String = afterFirstFall.random()
    fun afterSecondFall(): String = afterSecondFall.random()

    fun ordinary(): String = ordinary.random()

    /**
     * @param withMentorHint האם לצרף רמיזת-מלווה. מופעל בערך בשליש
     *        מהפעמים על-ידי הקורא, לא כאן, כדי שההחלטה תהיה גלויה.
     */
    fun atThreshold(withMentorHint: Boolean): String {
        val base = atThreshold.random()
        return if (withMentorHint) "$base\n\n${mentorHints.random()}" else base
    }
}
