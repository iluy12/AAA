package com.iluy.imutest

/**
 * קטגוריות הנפילה, והסדר שלהן במחווה.
 *
 * ## ⚠️ מה שהיה כאן ולמה הוסר
 *
 * זו הייתה `View` שהטמיעה את המחווה הרדיאלית **בתוך הרשימה במסך הראשי**,
 * והיא נכשלה בשלוש דרכים שכולן נבעו מאותה החלטה:
 *
 * 1. **הגרירה לא עבדה.** ה-ScrollView שמסביב יירט כל תנועה אנכית לפני
 *    שהגיעה לתצוגה — כלומר "ברית" ו"מחשבה", שיושבות למעלה ולמטה, היו
 *    בלתי-נגישות לחלוטין. הפיצ'ר נראה עובד ולא היה עובד.
 * 2. **הטקסט היה זעיר.** הגדלים נכתבו בפיקסלים גולמיים בלי להכפיל
 *    בצפיפות המסך.
 * 3. **צפוף.** ארבע בועות בתיבה נמוכה נדחסות זו לזו.
 *
 * המחווה עברה ל-[FallPickerActivity] כמסך מלא. **מה שנשאר כאן הוא רק
 * רשימת הקטגוריות**, כי היא מקור-האמת היחיד לסדר הכיוונים ולשמות —
 * ושכפול שלה למקום אחר היה מזמין את השניים להיפרד.
 */
object RadialFallButton {

    /**
     * מעלה · ימין · מטה · שמאל — בסדר הזה.
     *
     * ⚠️ הסדר מכוון: גרירה כלפי מעלה היא התנועה הטבעית ביותר, והיא שמורה
     * לחמורה. קרי לילה בשמאל — הרחוקה — כי היא הנדירה, והיא נבחרת בבוקר
     * בשקט ולא ברגע של מצוקה.
     *
     * ⚠️ **השמות חייבים להתאים ל-[FallSeverity.label]**, אחרת `fromLabel`
     * ייפול בשקט לברירת המחדל וכל בחירה תירשם כנפילה בברית.
     */
    val CATEGORIES = listOf("ברית", "עיניים", "מחשבה", "קרי לילה")
}
